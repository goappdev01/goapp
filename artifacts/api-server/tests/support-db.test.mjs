import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
const { PGlite } = createRequire(import.meta.url)('@electric-sql/pglite');

const admin = '11111111-1111-4111-8111-111111111111';
const alice = '22222222-2222-4222-8222-222222222222';
const bob = '33333333-3333-4333-8333-333333333333';
const business = '44444444-4444-4444-8444-444444444444';
const key = n => `55555555-5555-4555-8555-${String(n).padStart(12,'0')}`;

test('GO AYUDA isolated PostgreSQL: identity, queue, thread, audit, RLS, attachments and retries', async () => {
  const db = new PGlite();
  const query = (sql, params=[]) => db.query(sql,params);
  const user = async id => { await db.exec('reset role; set role authenticated;'); await query("select set_config('request.jwt.claim.sub',$1,false)",[id]); };
  const rpc = async (name,values) => (await query(`select public.${name}(${values.map((_,i)=>'$'+(i+1)).join(',')}) result`,values)).rows[0].result;
  try {
    await db.exec(`create role anon; create role authenticated; create schema auth;
      create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql stable as $$
        select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      grant usage on schema auth to authenticated; grant execute on function auth.uid() to authenticated;
      create table public.profiles(id uuid primary key,full_name text);
      create table public.businesses(id uuid primary key,owner_id uuid not null,verified boolean not null,name text);
      create table public.admin_memberships(user_id uuid primary key,level text,active boolean);
      create schema storage;
      create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
      create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text,metadata jsonb,unique(bucket_id,name));
      alter table storage.objects enable row level security;
      grant usage on schema storage to authenticated,anon;
      grant select,insert,delete on storage.objects to authenticated;`);
    await query('insert into auth.users(id) values($1),($2),($3)',[admin,alice,bob]);
    await query("insert into public.admin_memberships values($1,'owner',true)",[admin]);
    await query("insert into public.profiles values($1,'Synthetic Admin'),($2,'Synthetic Alice'),($3,'Synthetic Bob')",[admin,alice,bob]);
    await query("insert into public.businesses values($1,$2,true,'Synthetic Business')",[business,alice]);
    await db.exec(await readFile('supabase/drafts/go_support_v1.sql','utf8'));
    await user(alice);
    assert.equal((await rpc('go_support_readiness',[])).ready,true);
    const first = await rpc('go_support_create',["incident","SYNTHETIC issue",key(1),null]);
    assert.equal(first.status,'received'); assert.equal(first.reference,'AY-00000001');
    assert.equal(first.sender_name,'Synthetic Alice');
    assert.equal(first.retention_until,null);
    assert.equal((await rpc('go_support_create',["incident","SYNTHETIC issue",key(1),null])).id,first.id);
    await assert.rejects(rpc('go_support_create',["help","changed",key(1),null]), e => e.code==='PT409');
    const second = await rpc('go_support_create',["improvement","SYNTHETIC business improvement",key(2),business]);
    const personal=await rpc('go_support_list',[false,null,null,false,0,30,null,null,null,'personal',null]);
    const company=await rpc('go_support_list',[false,null,null,false,0,30,null,null,null,'business',business]);
    assert.equal(personal.total,1);assert.equal(personal.items[0].id,first.id);
    assert.equal(company.total,1);assert.equal(company.items[0].id,second.id);
    assert.equal((await rpc('go_support_list',[false,null,null,false,0,30])).total,2);
    await user(bob);
    await assert.rejects(rpc('go_support_list',[false,null,null,false,0,30,null,null,null,'business',business]),e=>e.code==='42501');
    await assert.rejects(rpc('go_support_detail',[first.id]),e=>e.code==='42501');
    assert.equal((await rpc('go_support_list',[false,null,null,false,0,30])).total,0);
    await assert.rejects(rpc('go_support_create',["help","spoof",key(3),business]),e=>e.code==='42501');
    await user(alice);
    const reserved = await rpc('go_support_reserve_file',[first.id,'local1','sample.pdf','application/pdf',12]);
    assert.equal(reserved.status,'uploading');
    await assert.rejects(rpc('go_support_confirm_file',[reserved.id]),e=>e.code==='22023');
    const file = await rpc('go_support_file',[reserved.id,'upload']);
    await query("insert into storage.objects(bucket_id,name,metadata) values('go-support-private',$1,$2)",
      [file.object_path,{size:12,mimetype:'application/pdf'}]);
    await rpc('go_support_confirm_file',[reserved.id]);
    assert.equal((await rpc('go_support_detail',[first.id])).files.length,1);
    await user(bob);
    await assert.rejects(rpc('go_support_file',[reserved.id,'read']),e=>e.code==='42501');
    assert.equal((await query('select * from storage.objects')).rows.length,0);
    await assert.rejects(query("insert into storage.objects(bucket_id,name,metadata) values('go-support-private',$1,$2)",
      [file.object_path,{size:12,mimetype:'application/pdf'}]),e=>e.code==='42501');
    await user(admin);
    assert.equal((await rpc('go_support_list',[true,null,null,false,0,30])).total,2);
    assert.equal((await rpc('go_support_list',[true,'received','improvement',false,0,30,'2000-01-01','2100-01-01','Alice'])).total,1);
    assert.equal((await rpc('go_support_list',[true,null,null,false,0,30,null,null,'Bob'])).total,0);
    const noted = await rpc('go_support_act',[first.id,key(4),'internal_note','SYNTHETIC internal',null,first.revision]);
    assert.equal(noted.messages[0].internal,true);
    const answered = await rpc('go_support_act',[first.id,key(5),'status','SYNTHETIC resolution','solved',noted.revision]);
    assert.equal(answered.status,'solved');
    assert.equal((await rpc('go_support_act',[first.id,key(5),'status','SYNTHETIC resolution','solved',noted.revision])).id,first.id);
    let archived = await rpc('go_support_act',[first.id,key(6),'archive',null,null,answered.revision]);
    assert.ok(archived.archived_at);
    assert.ok(Date.parse(archived.retention_until)>Date.parse(archived.archived_at)+364*86400000);
    assert.equal((await rpc('go_support_list',[true,null,null,false,0,30])).total,1);
    assert.equal((await rpc('go_support_list',[true,null,null,true,0,30])).total,1);
    const reopened = await rpc('go_support_act',[first.id,key(60),'reopen',null,null,archived.revision]);
    assert.equal(reopened.retention_until,null);assert.equal(reopened.archived_at,null);
    archived = await rpc('go_support_act',[first.id,key(61),'archive',null,null,reopened.revision]);
    await user(alice);
    const own = await rpc('go_support_detail',[first.id]);
    assert.equal(own.messages.length,1); assert.equal(own.messages[0].body,'SYNTHETIC resolution');
    assert.equal(own.history.length,5); assert.equal(own.history.some(event=>event.action==='internal_note'),false);
    assert.equal((await query('select * from public.go_support_messages where request_id=$1',[first.id])).rows.length,1);
    await assert.rejects(rpc('go_support_act',[first.id,key(7),'status','bad','rejected',archived.revision]),e=>e.code==='42501');
    await db.exec('reset role');
    await query('update public.businesses set owner_id=$1 where id=$2',[bob,business]);
    await user(alice);
    await assert.rejects(rpc('go_support_detail',[second.id]),e=>e.code==='42501');
    await db.exec('reset role');
    await query("update public.go_support_requests set retention_until=now()-interval '1 day' where id=$1",[first.id]);
    await user(admin);
    await assert.rejects(rpc('go_support_expired',[null]),e=>e.code==='22023');
    assert.equal((await rpc('go_support_expired',[20]))[0].id,first.id);
    assert.equal((await rpc('go_support_claim_expired',[first.id])).id,first.id);
    await assert.rejects(rpc('go_support_act',[first.id,key(62),'reopen',null,null,archived.revision]),e=>e.code==='PT409');
    await assert.rejects(rpc('go_support_purge_expired',[first.id]),e=>e.code==='PT409');
    assert.equal((await query("delete from storage.objects where bucket_id='go-support-private' and name=$1 returning id",[file.object_path])).rows.length,1);
    assert.equal(await rpc('go_support_purge_expired',[first.id]),true);
    assert.equal((await rpc('go_support_list',[true,null,null,true,0,30])).total,0);
    assert.equal((await query('select request_count from public.go_support_monthly_totals')).rows[0].request_count,1);
    await user(bob);
    assert.equal((await query('select * from public.go_support_monthly_totals')).rows.length,0);
  } finally { await db.close(); }
});
